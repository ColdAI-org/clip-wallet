// Listing-submission drafts for a kit-built wallet's own identity, written to docs/listings/. Nothing is submitted:
// each file says what the target registry wants, the exact entry for this wallet, and what to finish first. The
// formats follow each registry's docs as of the kit release (sources at the end of every file); check them again
// before you open a pull request.
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/**
 * @typedef {{ name: string, description: string, rdns: string, homepage?: string, extensionId: string, key: string,
 *   slug: string, networks: string[], version: string }} ListingIdentity
 */

const DRAFT = (/** @type {string} */ name) => `> DRAFT ONLY, generated by create-clip-wallet for ${name}. Nothing has been submitted. Regenerate with
> \`pnpm wallet:listings\` after you change wallet.identity.json, and check the registry's current rules first.`;

/** @param {ListingIdentity} id */
const site = (id) => id.homepage ?? `https://${id.rdns.split(".").slice(0, 2).reverse().join(".")}`;
/** @param {ListingIdentity} id */
const store = (id) => `https://chromewebstore.google.com/detail/${id.extensionId}`;
/** @param {ListingIdentity} id @param {string} family */
const has = (id, family) => id.networks.some((n) => n === family || n.startsWith(`${family}:`));

const PREREQS = (/** @type {ListingIdentity} */ id) => `## Before you submit anything
- [ ] The extension is published on the Chrome Web Store under id \`${id.extensionId}\` (fixed by \`extension.key\` in
      wallet.identity.json; keep .keys/extension.pem safe and out of git).
- [ ] \`${site(id)}\` is live and says who runs ${id.name}, how recovery works (the phrase never leaves the device) and
      how to get support. ${id.homepage ? "" : "Set `homepage` in wallet.identity.json: this placeholder is derived from the rdns."}
- [ ] You own the domain behind \`${id.rdns}\`.
- [ ] Icons are hosted at stable https URLs you control (PNG, square).
- [ ] Registries list production wallets: finish MAINNET.md first.`;

/** @param {ListingIdentity} id */
function eip6963(id) {
  return `# EIP-6963 identity: ${id.name}

${DRAFT(id.name)}

EIP-6963 has no central registry: a wallet announces itself on every page with \`eip6963:announceProvider\`, and dapps
(wagmi, RainbowKit, Web3Modal/AppKit, ConnectKit, Web3-Onboard) list whatever answers. What has to be right is what
${id.name} announces, and that nobody else announces the same rdns.

| Field | Value | Where it comes from |
| --- | --- | --- |
| \`info.name\` | ${id.name} | wallet.identity.json \`name\` |
| \`info.rdns\` | \`${id.rdns}\` | wallet.identity.json \`rdns\` (a reverse domain you own) |
| \`info.icon\` | data:image/svg+xml;base64,… | icon.svg (next to clip.config.ts), inlined at build time |
| \`info.uuid\` | a fresh UUIDv4 per page load | 1Mask |
| Chrome extension id | \`${id.extensionId}\` | wallet.identity.json \`extension.key\` |

${id.name} never announces \`org.coldai.clipwallet\` (Clip Wallet's own rdns) and never claims \`window.ethereum\` unless
nothing else owns it.

## How dapps target it
\`\`\`ts
// wagmi: EIP-6963 discovery is on by default; to show only ${id.name}:
import { injected } from "wagmi/connectors";
injected({ target: { id: "${id.rdns}", name: "${id.name}", provider: () => undefined } });
// or find it in the store: createStore() from "mipd", then store.findProvider({ rdns: "${id.rdns}" })
\`\`\`

## Places that key on the rdns
- WalletConnect Explorer listing: the \`rdns\` field (see walletconnect-explorer.md) lets AppKit merge the injected
  wallet with its listing instead of showing it twice.
- Wallet lists that ship static metadata (e.g. RainbowKit wallet packs) match on the rdns.

${PREREQS(id)}

## Sources
- https://eips.ethereum.org/EIPS/eip-6963
- https://github.com/wevm/mipd
- https://wagmi.sh/core/api/connectors/injected
`;
}

/** @param {ListingIdentity} id */
function walletConnect(id) {
  const chains = [];
  if (id.networks.some((n) => n.startsWith("evm:"))) chains.push("eip155:1", "eip155:8453", "eip155:295");
  if (has(id, "hedera")) chains.push("hedera:mainnet");
  if (has(id, "solana")) chains.push("solana:5eykt4UsFv8P8NJdTREpY1vzqKqZKvdp");
  if (has(id, "bitcoin")) chains.push("bip122:000000000019d6689c085ae165831e93");
  const entry = {
    name: id.name,
    description: id.description,
    homepage: site(id),
    image_url: `${site(id)}/walletconnect-icon-512.png`,
    rdns: id.rdns,
    injected: [{ namespace: "eip155", injected_id: id.rdns }],
    app: { browser: store(id) },
    chains,
    supported_standards: ["eip-6963", "walletconnect-v2"],
  };
  return `# WalletConnect Explorer (Reown) listing: ${id.name}

${DRAFT(id.name)}

Wallets are listed in the WalletConnect Explorer (the wallet list AppKit and WalletConnect-powered dapps show) through
the Reown dashboard: cloud.reown.com, your wallet project, "Get listed". Reown reviews the submission and tests the
wallet. ${id.name}'s WalletConnect side uses its own project id (CLIP_WALLETCONNECT_PROJECT_ID in .env,
never committed); the Explorer listing belongs to that same project.

## Draft entry
\`\`\`json
${JSON.stringify(entry, null, 2)}
\`\`\`

Notes:
- \`rdns\` and \`injected_id\` are the EIP-6963 rdns, so AppKit shows one ${id.name} entry for the extension and for
  WalletConnect, not two.
- \`chains\` must only list mainnets ${id.name} supports in its release build (CAIP-2). Test networks are not listed.
- The WalletConnect metadata the extension sends (name, url, icons) comes from wallet.identity.json; \`url\` is
  \`${site(id)}\`.
- Reown asks for a 512×512 PNG icon and a short demo of connecting and signing.

${PREREQS(id)}

## Sources
- https://docs.reown.com/cloud/explorer-submission
- https://docs.reown.com/walletkit/overview
`;
}

