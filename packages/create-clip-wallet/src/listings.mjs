/**
 * Write the drafts for the families this wallet turns on. Returns the files written (relative to root).
 * @param {string} root @param {ListingIdentity} id
 */
export function writeListings(root, id) {
  const dir = join(root, "docs", "listings");
  mkdirSync(dir, { recursive: true });
  /** @type {[string, string, boolean, string][]} file, title, applies, why not */
  const all = [
    ["eip-6963.md", "EIP-6963 identity (every EVM dapp)", id.networks.some((n) => n.startsWith("evm:")), "EVM is off"],
    ["walletconnect-explorer.md", "WalletConnect Explorer (Reown)", true, ""],
    ["ton-connect.md", "TON Connect wallets-list", has(id, "ton"), "TON is off"],
    ["near.md", "NEAR Connect / NEAR Wallet Selector", has(id, "near"), "NEAR is off"],
    ["stellar-wallets-kit.md", "Stellar Wallets Kit", has(id, "stellar"), "Stellar is off"],
    ["beacon.md", "Tezos Beacon wallet list", has(id, "tezos"), "Tezos is off"],
    ["use-wallet.md", "Algorand use-wallet", has(id, "algorand"), "Algorand is off"],
  ];
  const render = { "eip-6963.md": eip6963, "walletconnect-explorer.md": walletConnect, "ton-connect.md": tonConnect, "near.md": near, "stellar-wallets-kit.md": stellar, "beacon.md": beacon, "use-wallet.md": useWallet };
  const written = [];
  for (const [file, , applies] of all) {
    if (!applies) continue;
    writeFileSync(join(dir, file), render[/** @type {keyof typeof render} */ (file)](id));
    written.push(join("docs", "listings", file));
  }
  const rows = all.map(([file, title, applies, why]) => `| ${title} | ${applies ? `[${file}](${file})` : `not drafted: ${why} in clip.config.ts`} |`);
  writeFileSync(
    join(dir, "README.md"),
    `# Listing drafts for ${id.name}

${DRAFT(id.name)}

| | |
| --- | --- |
| Name | ${id.name} |
| rdns (EIP-6963) | \`${id.rdns}\` |
| Chrome extension id | \`${id.extensionId}\` |
| Wallet key (window global, TON Connect) | \`${id.key}\` |
| Website | ${site(id)} |
| Kit version | @clip-wallet/extension-kit ${id.version} |

| Registry | Draft |
| --- | --- |
${rows.join("\n")}

${PREREQS(id)}
`,
  );
  written.unshift(join("docs", "listings", "README.md"));
  return written;
}
