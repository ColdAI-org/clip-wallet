#!/usr/bin/env node
/**
 * Everything the docs build generates from the repository, so it can't drift from the code:
 *
 *   1. brand assets: brand/*.svg and the ColdAI logos into src/public/brand
 *   2. test reports: docs/r1/dapp-matrix.md and picker-matrix.md into src/testing/results (links rewritten)
 *   3. reference pages from the source: config schema, error, warning and dapp error codes (scripts/reference.ts)
 *   4. the create-clip-wallet CLI page, from its own --help
 *   5. the API reference: TypeDoc over every published package's exports (scripts/typedoc.mjs)
 *
 *   node scripts/generate.mjs [--no-api]
 */
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { runTypedoc } from "./typedoc.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const docs = join(here, "..");
const root = join(docs, "..", "..");
const src = join(docs, "src");
const started = Date.now();

/* 1. brand */
const brandOut = join(src, "public", "brand");
rmSync(brandOut, { recursive: true, force: true });
mkdirSync(brandOut, { recursive: true });
for (const f of readdirSync(join(root, "brand"))) if (f.endsWith(".svg")) copyFileSync(join(root, "brand", f), join(brandOut, f));
for (const f of ["coldai-logo-dark.png", "coldai-logo-white.png"]) copyFileSync(join(root, ".github", "assets", f), join(brandOut, f));

/* 2. test reports */
const resultsOut = join(src, "testing", "results");
rmSync(resultsOut, { recursive: true, force: true });
mkdirSync(resultsOut, { recursive: true });
const REPORTS = { "dapp-matrix.md": "dapp-matrix.md", "picker-matrix.md": "picker-matrix.md" };
for (const [from, to] of Object.entries(REPORTS)) {
  let text = readFileSync(join(root, "docs", "r1", from), "utf8");
  // Links between the two reports stay inside the site; the funding notes and every other relative link point
  // at the repository (repo: links are checked at build time).
  text = text.replace(/\]\((?!https?:|#|repo:)([^)\s]+)\)/g, (whole, target) => {
    const [path, hash] = target.split("#");
    if (REPORTS[path]) return `](./${REPORTS[path]}${hash ? `#${hash}` : ""})`;
    if (path === "dapp-matrix-funding.md") return `](../test-wallet.md)`;
    return `](repo:${join("docs/r1", path).replace(/\\/g, "/")}${hash ? `#${hash}` : ""})`;
  });
  const banner =
    "<!-- Copied from docs/r1 by apps/docs/scripts/generate.mjs. Edit the original. -->\n\n" +
    `::: info Test report\nThis page is the report the matrix run wrote, copied from [docs/r1/${from}](repo:docs/r1/${from}). ` +
    "For how to run it yourself, see [Dapp and picker matrices](../matrices.md).\n:::\n\n";
  // Placeholders like <site> outside code are text on GitHub, but VitePress compiles pages as Vue templates.
  let fenced = false;
  text = text
    .split("\n")
    .map((line) => {
      if (line.startsWith("```")) fenced = !fenced;
      if (fenced) return line;
      return line
        .split(/(`[^`]*`)/)
        .map((part) => (part.startsWith("`") ? part : part.replace(/<([a-z][\w-]*)>/gi, "&lt;$1&gt;")))
        .join("");
    })
    .join("\n");
  // The report's first heading stays the page title.
  const [first, ...rest] = text.split("\n");
  writeFileSync(join(resultsOut, to), `${first}\n\n${banner}${rest.join("\n")}`);
}

/* 3. reference pages from the source */
// Under node_modules so pnpm harness and git never see the bundled generator.
const cache = join(docs, "node_modules", ".cache", "clip-docs");
mkdirSync(cache, { recursive: true });
await build({
  entryPoints: [join(here, "reference.ts")],
  outfile: join(cache, "reference.mjs"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  conditions: ["development"],
  external: ["typescript"],
  logLevel: "warning",
});
execFileSync(process.execPath, [join(cache, "reference.mjs"), root, join(src, "reference")], { stdio: "inherit", cwd: docs });

/* 4. create-clip-wallet --help */
const help = execFileSync(process.execPath, ["--conditions=development", join(root, "packages/create-clip-wallet/bin/create-clip-wallet.mjs"), "--help"], {
  encoding: "utf8",
  cwd: root,
});
writeFileSync(
  join(src, "reference", "cli.md"),
  `<!-- Generated by apps/docs/scripts/generate.mjs from create-clip-wallet --help. -->
# create-clip-wallet CLI

The command-line reference, printed by the CLI itself (\`npx create-clip-wallet --help\`). For a walkthrough, see
[create-clip-wallet](../kit/create-clip-wallet.md).

\`\`\`text
${help.trimEnd()}
\`\`\`

## Exit codes

| Command | Exit code |
| --- | --- |
| \`create-clip-wallet <folder>\`, \`identity\`, \`listings\` | \`0\` done, \`1\` refused (the reason is printed in plain words) |
| \`create-clip-wallet mainnet-check\` | \`0\` ready, \`2\` work left, \`1\` mainnet is on but not ready |
`,
);

/* 5. API reference */
if (!process.argv.includes("--no-api")) await runTypedoc({ root, out: join(src, "reference", "api") });

console.log(`docs: generated in ${((Date.now() - started) / 1000).toFixed(1)} s`);
