function sourceFiles(dir: string): string[] {
  const outFiles: string[] = [];
  const walk = (d: string) => {
    for (const e of readdirSync(d)) {
      if (e === "node_modules" || e === "dist" || e === "test" || e === "vendor") continue;
      const p = join(d, e);
      const st = statSync(p);
      if (st.isDirectory()) walk(p);
      else if (/\.(ts|tsx)$/.test(e) && !/\.(test|d)\.tsx?$/.test(e)) outFiles.push(p);
    }
  };
  walk(dir);
  return outFiles;
}

function packageOf(file: string): string {
  const rel = relative(root, file).split("/");
  const pj = JSON.parse(readFileSync(join(root, rel[0]!, rel[1]!, "package.json"), "utf8")) as { name: string };
  return pj.name;
}

interface ErrorSite {
  code: string;
  pkg: string;
  message?: string;
}

/** Every `new ClipError(message, "code", …)` with a literal (or template) code in packages/*\/src. */
function scanClipErrors(): ErrorSite[] {
  const sites: ErrorSite[] = [];
  const files = readdirSync(join(root, "packages")).flatMap((p) => {
    const src = join(root, "packages", p, "src");
    try {
      return statSync(src).isDirectory() ? sourceFiles(src) : [];
    } catch {
      return [];
    }
  });
  for (const f of files) {
    const text = readFileSync(f, "utf8");
    if (!text.includes("ClipError(")) continue;
    const sf = ts.createSourceFile(f, text, ts.ScriptTarget.Latest, true, f.endsWith("x") ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
    const visit = (n: ts.Node) => {
      if (ts.isNewExpression(n) && ts.isIdentifier(n.expression) && n.expression.text === "ClipError" && n.arguments && n.arguments.length >= 2) {
        const [m, c] = n.arguments as unknown as [ts.Expression, ts.Expression];
        let codeText: string | undefined;
        if (ts.isStringLiteral(c) || ts.isNoSubstitutionTemplateLiteral(c)) codeText = c.text;
        else if (ts.isTemplateExpression(c)) codeText = c.head.text + c.templateSpans.map((s) => `<${s.expression.getText(sf)}>${s.literal.text}`).join("");
        if (codeText) {
          const message = ts.isStringLiteral(m) || ts.isNoSubstitutionTemplateLiteral(m) ? m.text : undefined;
          sites.push({ code: codeText, pkg: packageOf(f), ...(message ? { message } : {}) });
        }
      }
      ts.forEachChild(n, visit);
    };
    visit(sf);
  }
  return sites;
}

