type Json = {
  type?: string | string[];
  properties?: Record<string, Json>;
  required?: string[];
  default?: unknown;
  enum?: unknown[];
  const?: unknown;
  pattern?: string;
  minimum?: number;
  maximum?: number;
  minLength?: number;
  maxLength?: number;
  minItems?: number;
  items?: Json;
  anyOf?: Json[];
};

function typeOf(s: Json): string {
  if (s.anyOf) return s.anyOf.map(typeOf).filter((t) => t !== "unknown").join(" \\| ") || "unknown";
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" \\| ");
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.type === "array") return `${s.items ? typeOf(s.items) : "unknown"}[]`;
  if (Array.isArray(s.type)) return s.type.join(" \\| ");
  return s.type ?? "unknown";
}

function rulesOf(s: Json): string[] {
  const r: string[] = [];
  if (s.minLength !== undefined || s.maxLength !== undefined) r.push(`${s.minLength ?? 0} to ${s.maxLength ?? "∞"} characters`);
  if (s.minimum !== undefined || s.maximum !== undefined) r.push(`${s.minimum ?? "−∞"} to ${s.maximum ?? "∞"}`);
  if (s.minItems !== undefined) r.push(`at least ${s.minItems}`);
  return r;
}

