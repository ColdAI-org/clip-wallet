// Bundles src/plugins/sandbox-entry.ts (SES + the plugin runtime) into the inline sandbox page the plugin WebViews
// load. Output: src/plugins/sandbox.generated.ts (gitignored). Run by build-inpage.mjs (start/typecheck/test/export).
//
// The page has a Content-Security-Policy that allows exactly this script (by its sha256 hash) plus eval (SES
// compartments evaluate the plugin's source), and nothing else: no network, frames, workers, images, styles,
// forms or base URL. JavaScript-initiated network is also impossible from the compartment (no fetch/XHR/WebSocket
// globals); the CSP is the second wall.
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = await build({
  entryPoints: [join(root, "src/plugins/sandbox-entry.ts")],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: ["safari15", "chrome100"],
  minify: true,
  legalComments: "none",
  logLevel: "warning",
  // Workspace packages: their "development" export condition is the TypeScript source (no build needed).
  conditions: ["development"],
});
// Inline <script>: never let the bundle close the tag early.
const js = out.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const hash = createHash("sha256").update(js, "utf8").digest("base64");
export const SANDBOX_CSP = [
  "default-src 'none'",
  `script-src 'sha256-${hash}' 'unsafe-eval'`,
  "connect-src 'none'",
  "img-src 'none'",
  "style-src 'none'",
  "font-src 'none'",
  "media-src 'none'",
  "object-src 'none'",
  "frame-src 'none'",
  "child-src 'none'",
  "worker-src 'none'",
  "manifest-src 'none'",
  "form-action 'none'",
  "base-uri 'none'",
].join("; ");
const html =
  `<!doctype html><html><head><meta charset="utf-8">` +
  `<meta http-equiv="Content-Security-Policy" content="${SANDBOX_CSP}">` +
  `<meta name="referrer" content="no-referrer"><title>Plugin sandbox</title></head>` +
  `<body><script>${js}</script></body></html>`;
const file = join(root, "src/plugins/sandbox.generated.ts");
mkdirSync(dirname(file), { recursive: true });
writeFileSync(
  file,
  `// GENERATED by scripts/build-plugin-sandbox.mjs from src/plugins/sandbox-entry.ts. Do not edit.\n` +
    `export const PLUGIN_SANDBOX_JS: string = ${JSON.stringify(js)};\n` +
    `export const PLUGIN_SANDBOX_CSP: string = ${JSON.stringify(SANDBOX_CSP)};\n` +
    `export const PLUGIN_SANDBOX_HTML: string = ${JSON.stringify(html)};\n`,
);
console.log(`plugin sandbox page: ${(html.length / 1024).toFixed(1)} KiB`);
